def prime_gen():
    def is_prime(a):
        if a < 2:
            return False
        for i in range(2, int(a**0.5) + 1):
            if a % i == 0:
                return False
        return True

    a = 2
    while True:
        if is_prime(a):
            yield a
        a += 1
